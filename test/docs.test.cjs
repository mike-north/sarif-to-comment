'use strict';

/**
 * Documentation tests: README, getting-started guide and generated API
 * reference are accurate, reachable and executable.
 *
 * - README links work on the npm package page even though the source
 *   repository is private: every link is absolute (or an in-page anchor), and
 *   links to packaged documents point at files that are in the tarball.
 * - The getting-started guide's library and CLI examples are extracted
 *   verbatim and run against the *installed* package, with the real GitHub
 *   client talking HTTP to the fake GitHub in test/fixtures/composition (the
 *   example code is unchanged; only `fetch` is replaced by a preload). A retry
 *   with the same state path must not publish again, and the CLI example's
 *   outcome handling must report a blocked document.
 * - The API reference is generated by API Documenter from API Extractor's doc
 *   model (never hand-written), navigable (every relative link resolves), and
 *   the staleness check detects a declaration change that was not regenerated.
 *
 * @see https://api-extractor.com/pages/setup/generating_docs/
 * @see https://api-extractor.com/pages/setup/invoking/
 * @see https://docs.npmjs.com/cli/v11/configuring-npm/package-json#repository
 */

const test = require('node:test');
const { describe } = test;
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { spawnSync } = require('node:child_process');

const { ROOT, packProject, installIntoConsumer } = require('./fixtures/package/installed-package.cjs');
const { FakeHttpGitHub, REPOSITORY } = require('./fixtures/composition/fake-http-github.cjs');

const README = fs.readFileSync(path.join(ROOT, 'README.md'), 'utf8');
const GUIDE_PATH = path.join(ROOT, 'docs', 'getting-started.md');
const GUIDE = fs.existsSync(GUIDE_PATH) ? fs.readFileSync(GUIDE_PATH, 'utf8') : '';
const API_DIR = path.join(ROOT, 'docs', 'api');
const PRELOAD = path.join(ROOT, 'test', 'fixtures', 'docs', 'fake-fetch-preload.cjs');
const PACKAGE_DOCS_BASE = 'https://unpkg.com/sarif-to-comment/';

/** Every Markdown link target in `text` (inline links; code spans and fences excluded). */
function linkTargets(text) {
  const prose = text.replace(/```[\s\S]*?```/g, '').replace(/`[^`\n]*`/g, '');
  return [...prose.matchAll(/\]\(([^)\s]+)(?:\s+"[^"]*")?\)/g)].map((m) => m[1]);
}

/** The fenced code block that follows `<!-- verified-example: name -->`. */
function example(text, name) {
  const match = new RegExp(`<!-- verified-example: ${name} -->\\s*\\n\`\`\`(\\w+)\\n([\\s\\S]*?)\\n\`\`\``).exec(text);
  assert.ok(match, `the guide has a verified ${name} example`);
  return { language: match[1], code: match[2] };
}

describe('README', () => {
  test('every link works on the npm page of a private repository (absolute or in-page)', () => {
    const targets = linkTargets(README);
    assert.ok(targets.length > 5);
    for (const target of targets) {
      assert.ok(/^https:\/\//.test(target) || target.startsWith('#'), `relative link would break on npm: ${target}`);
      assert.doesNotMatch(target, /github\.com\/mike-north\/sarif-to-comment/, `the source repository is private: ${target}`);
    }
  });

  test('in-page anchors name real headings', () => {
    const slugs = new Set(
      [...README.matchAll(/^#{1,6} (.+)$/gm)].map((m) =>
        m[1].trim().toLowerCase().replace(/[^\w\- ]/g, '').replace(/ /g, '-'),
      ),
    );
    for (const target of linkTargets(README).filter((t) => t.startsWith('#'))) {
      assert.ok(slugs.has(target.slice(1)), `no heading for ${target}`);
    }
  });

  test('links to packaged documents point at files in the tarball', { skip: packProject().error || false }, () => {
    const files = new Set(packProject().result.files.map((f) => f.path));
    const packaged = linkTargets(README).filter((t) => t.startsWith(PACKAGE_DOCS_BASE));
    assert.ok(packaged.some((t) => t.endsWith('docs/getting-started.md')), 'README links the getting-started guide');
    assert.ok(packaged.some((t) => t.endsWith('docs/api/index.md')), 'README links the API reference');
    for (const target of packaged) {
      const file = target.slice(PACKAGE_DOCS_BASE.length).replace(/#.*$/, '');
      assert.ok(files.has(file), `${file} is linked but not packaged`);
    }
  });

  test('shows both surfaces and states the semantics consumers rely on', () => {
    assert.match(README, /```js[\s\S]*publishSarifReview/);
    assert.match(README, /```sh[\s\S]*sarif-to-comment[\s\\]*--sarif/);
    assert.match(README, /draft/i);
    assert.match(README, /one-way/i);
    assert.match(README, /GH_TOKEN/);
    assert.match(README, /trusted publishing/i);
  });
});

